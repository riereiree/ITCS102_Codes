#Operators 
#Arithmetic Operator

a = 17
b = 3

#+ - Addition
sum = a + b

print("The sum of",a,"and",b,"is", sum)

#- - Subtraction
diff = a - b

print("The difference of",a,"and",b,"is", diff)

#* - Multiplication
prod = a * b

print("The product of",a,"and",b,"is", prod)

#/ - Division
quo= a / b

print("The quotient of",a,"and",b,"is", quo)

#// - Floor Division
fd = a // b

print("The floor division quotient of",a,"and",b,"is", fd)

#** - Exponentation
expo = a**b

print("The exponenation of",a,"and",b,"is", expo)

#% - Modulus
mod = a % b
print("The modulus answer of",a,"and",b,"is", mod)